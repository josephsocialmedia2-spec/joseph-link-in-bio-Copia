"""Synthetic-only SQLite workflow for the Zero to Diamond isolated staging lab.

Intentionally NOT a production CRM adapter: creates only reserved .test identities,
never sends mail/WhatsApp, never accesses external services or real contact files.
"""
from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit
import re

SOURCES = ("volantino-qr", "catalogo-premium", "rivista-lettera", "landing-test")
SCENARIOS = ("venditore", "acquirente", "referenza")
STATES = ("NUOVO", "QUALIFICATO", "FOLLOW_UP", "APPUNTAMENTO", "TRASFERITO", "CHIUSO", "NON_CONTATTARE")
ACTIONS = ("qualify", "followup", "appointment", "handoff", "close", "stop")
SCHEMA = """
CREATE TABLE IF NOT EXISTS leads (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  source TEXT NOT NULL,
  scenario TEXT NOT NULL,
  status TEXT NOT NULL,
  marketing_optin INTEGER NOT NULL CHECK(marketing_optin IN (0,1)),
  transfer_optin INTEGER NOT NULL CHECK(transfer_optin IN (0,1)),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  lead_id INTEGER,
  action TEXT NOT NULL,
  outcome TEXT NOT NULL,
  detail TEXT NOT NULL,
  created_at TEXT NOT NULL,
  FOREIGN KEY(lead_id) REFERENCES leads(id)
);
"""

class LabError(Exception):
    def __init__(self, code: str, message: str, status: int = 422):
        super().__init__(message)
        self.code, self.status = code, status

def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")

def true_bool(value) -> bool:
    return type(value) is bool

class SyntheticCRM:
    def __init__(self, db_path: Path):
        self.path = Path(db_path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as conn:
            conn.executescript(SCHEMA)

    def connect(self):
        conn = sqlite3.connect(str(self.path), timeout=5)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        return conn

    def event(self, conn, lead_id, action, outcome="simulated", detail=""):
        conn.execute("INSERT INTO events (lead_id,action,outcome,detail,created_at) VALUES (?,?,?,?,?)",
                     (lead_id, action, outcome, detail, now()))

    @staticmethod
    def public_lead(row):
        return {key: (bool(row[key]) if key in ("marketing_optin", "transfer_optin") else row[key])
                for key in ("id", "name", "email", "source", "scenario", "status",
                            "marketing_optin", "transfer_optin", "created_at", "updated_at")}

    @staticmethod
    def check_bool(payload, key):
        if not true_bool(payload.get(key)):
            raise LabError("invalid_input", f"{key} deve essere true oppure false")
        return payload[key]

    def create(self, data):
        # Never accept names, phone numbers, addresses or external contact records.
        if set(data) != {"source", "scenario", "marketing_optin", "transfer_optin"}:
            raise LabError("synthetic_fields_only", "Sono consentite soltanto opzioni predefinite, non dati personali")
        source, scenario = data.get("source"), data.get("scenario")
        if source not in SOURCES or scenario not in SCENARIOS:
            raise LabError("invalid_input", "Seleziona una fonte e uno scenario sintetico consentiti")
        marketing = self.check_bool(data, "marketing_optin")
        transfer = self.check_bool(data, "transfer_optin")
        stamp = now()
        with self.connect() as db:
            # Serialised transaction: each fake identity is generated by the database itself.
            db.execute("BEGIN IMMEDIATE")
            cur = db.execute(
                """INSERT INTO leads (name,email,source,scenario,status,
                   marketing_optin,transfer_optin,created_at,updated_at)
                   VALUES ('PENDING','pending-' || lower(hex(randomblob(12))) || '@example.test',?,?,
                           'NUOVO',?,?,?,?)""",
                (source, scenario, int(marketing), int(transfer), stamp, stamp))
            lead_id = cur.lastrowid
            db.execute("UPDATE leads SET name=?, email=? WHERE id=?",
                       (f"TEST {scenario.capitalize()} {lead_id:04d}", f"lead{lead_id:04d}@example.test", lead_id))
            self.event(db, lead_id, "request", detail=f"{source}:{scenario}")
            return self.public_lead(db.execute("SELECT * FROM leads WHERE id=?", (lead_id,)).fetchone())

    def _load(self, db, lead_id):
        row = db.execute("SELECT * FROM leads WHERE id=?", (lead_id,)).fetchone()
        if row is None:
            raise LabError("not_found", "Contatto di prova inesistente", status=404)
        return row

    def action(self, lead_id, operation, data):
        if operation not in ACTIONS and operation != "permissions":
            raise LabError("not_found", "Azione non disponibile", status=404)
        with self.connect() as db:
            db.execute("BEGIN IMMEDIATE")
            lead = self._load(db, lead_id)
            old = lead["status"]
            if operation == "permissions":
                if set(data) != {"marketing_optin", "transfer_optin"}:
                    raise LabError("synthetic_fields_only", "Non inserire dati personali nei permessi di prova")
                if old in ("NON_CONTATTARE", "CHIUSO"):
                    raise LabError("locked", "Il contatto è chiuso o non contattabile", status=409)
                marketing = self.check_bool(data, "marketing_optin")
                transfer = self.check_bool(data, "transfer_optin")
                db.execute("UPDATE leads SET marketing_optin=?,transfer_optin=?,updated_at=? WHERE id=?",
                           (int(marketing), int(transfer), now(), lead_id))
                self.event(db, lead_id, "permissions", detail=f"marketing={int(marketing)},transfer={int(transfer)}")
            else:
                if data:
                    raise LabError("synthetic_fields_only", "Le azioni sono predefinite; testo libero non consentito")
                transitions = {
                    "qualify": (("NUOVO",), "QUALIFICATO"),
                    "followup": (("QUALIFICATO", "FOLLOW_UP"), "FOLLOW_UP"),
                    "appointment": (("QUALIFICATO", "FOLLOW_UP"), "APPUNTAMENTO"),
                    "handoff": (("QUALIFICATO", "FOLLOW_UP", "APPUNTAMENTO"), "TRASFERITO"),
                    "close": (("TRASFERITO",), "CHIUSO"),
                    "stop": (("NUOVO", "QUALIFICATO", "FOLLOW_UP", "APPUNTAMENTO", "TRASFERITO"), "NON_CONTATTARE"),
                }
                permitted, target = transitions[operation]
                if old not in permitted:
                    raise LabError("invalid_transition", f"Transizione non consentita da {old}", status=409)
                if operation == "followup" and not lead["marketing_optin"]:
                    self.event(db, lead_id, "followup", "blocked", "No marketing opt-in")
                    # Log the negative test without altering lead status.
                    db.commit()
                    raise LabError("consent_required", "Follow-up promozionale bloccato: consenso assente", status=409)
                if operation == "handoff" and not lead["transfer_optin"]:
                    self.event(db, lead_id, "handoff", "blocked", "No partner transfer permission")
                    db.commit()
                    raise LabError("transfer_required", "Trasferimento bloccato: autorizzazione assente", status=409)
                updates = "status=?,updated_at=?"
                params = [target, now()]
                if operation == "stop":
                    updates += ",marketing_optin=0,transfer_optin=0"
                db.execute(f"UPDATE leads SET {updates} WHERE id=?", (*params, lead_id))
                self.event(db, lead_id, operation, detail=f"{old}>{target}")
            return self.public_lead(self._load(db, lead_id))

    def state(self):
        with self.connect() as db:
            leads = [self.public_lead(x) for x in
                     db.execute("SELECT * FROM leads ORDER BY id DESC LIMIT 200").fetchall()]
            events = [dict(x) for x in
                      db.execute("SELECT * FROM events ORDER BY id DESC LIMIT 60").fetchall()]
            all_leads = db.execute("SELECT COUNT(*) FROM leads").fetchone()[0]
            counts = {status: db.execute("SELECT COUNT(*) FROM leads WHERE status=?", (status,)).fetchone()[0]
                      for status in STATES}
            event_counts = {action: db.execute(
                "SELECT COUNT(*) FROM events WHERE action=? AND outcome='simulated'", (action,)
            ).fetchone()[0] for action in ("request", "followup", "appointment", "handoff", "close")}
            blocked = db.execute("SELECT COUNT(*) FROM events WHERE outcome='blocked'").fetchone()[0]
        return {"mode": "SYNTHETIC_ONLY", "simulated": True, "external_deliveries": 0,
                "database": "SQLite isolato (nessuna sincronizzazione)",
                "leads": leads, "events": events,
                "kpi": {"requests": all_leads,
                        "qualified_current": counts["QUALIFICATO"],
                        "followups_simulated": event_counts["followup"],
                        "appointments_simulated": event_counts["appointment"],
                        "handoffs_simulated": event_counts["handoff"],
                        "closed_simulated": event_counts["close"],
                        "blocked_by_policy": blocked,
                        "non_contactable": counts["NON_CONTATTARE"],
                        "marketing_optins": sum(int(x["marketing_optin"]) for x in leads)}}

    def reset(self):
        with self.connect() as db:
            db.execute("DELETE FROM events")
            db.execute("DELETE FROM leads")
            db.execute("DELETE FROM sqlite_sequence WHERE name IN ('leads','events')")
        return self.state()
