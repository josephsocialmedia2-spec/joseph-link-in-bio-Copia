'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('catalogo-premium/index.html');
const js=read('catalogo-premium/catalogo.js');
const css=read('catalogo-premium/style.css');
const Rules=require('../catalogo-premium/property-rules.js');
const feed=JSON.parse(read('immobili/catalogo.json')).items;
const all=Rules.filterListings(feed);
test('the official catalogue is complete and not silently filtered',()=>{
 assert.doesNotThrow(()=>new vm.Script(js));
 assert.equal(all.length,feed.length);
 assert.ok(all.length>=50);
 assert.ok(all.every(x=>Rules.originalUrl(x.url)));
 assert.ok(all.some(x=>x.municipality==='Borgaro Torinese'));
 assert.ok(all.some(x=>!x.municipality));
 assert.ok(all.some(x=>/in[-_ ]trattativa/i.test(x.image||'')));
 assert.ok(all.some(x=>x.category==='Impresa'));
 assert.ok(all.some(x=>/terren/i.test(x.title)));
 assert.match(js,/Rules\.filterListings\(data\.items/);
 assert.doesNotMatch(js,/onlyVerified|verifiedOnly/);
 assert.doesNotMatch(html,/Solo annunci con APE verificato|26 proposte residenziali nei comuni ammessi/);
});
test('category and municipality are derived and filtered only on demand',()=>{
 const facets=Rules.facets(feed);
 assert.ok(facets.categories.includes('Commerciale'));
 assert.ok(facets.categories.includes('Residenziale'));
 assert.ok(facets.categories.includes('Terreno'));
 assert.ok(facets.municipalities.includes('Borgaro Torinese'));
 assert.ok(facets.municipalities.includes('Comune da verificare'));
 assert.ok(facets.statuses.includes('Disponibile'));
 assert.ok(Rules.filterListings(feed,{category:'Commerciale'}).every(x=>Rules.categoryOf(x)==='Commerciale'));
 assert.ok(Rules.filterListings(feed,{municipality:'Borgaro Torinese'}).every(x=>Rules.municipalityOf(x)==='Borgaro Torinese'));
 assert.ok(Rules.filterListings(feed,{municipality:'Comune da verificare'}).every(x=>!Rules.municipalityOf(x)));
 assert.ok(Rules.filterListings(feed,{status:'Disponibile'}).length>0);
 const first=feed[0],second=feed[1];
 assert.deepEqual(Rules.filterListings(feed,{ids:[String(second.id),String(first.id)]}).map(x=>String(x.id)),[String(second.id),String(first.id)]);
 for(const id of ['categoryFilter','townFilter','statusFilter'])assert.ok(html.includes('id="'+id+'"'));
 assert.match(js,/url\.searchParams\.set\(key,input\.value\)/);
});
test('agency-maintained state takes precedence; image name is not a status source',()=>{
 const contradictory=feed.find(p=>/in[-_ ]trattativa/i.test(p.image||''));
 assert.ok(contradictory);
 assert.equal(Rules.statusOf(contradictory),'Disponibile');
 assert.equal(Rules.statusOf({...contradictory,agency_status:'IN_TRATTATIVA'}),'In trattativa');
 assert.equal(Rules.statusOf({...contradictory,listing_status:'SOLD'}),'Venduto');
 assert.equal(Rules.statusOf({...contradictory,availability_status:null}),'Stato da confermare');
 assert.equal(Rules.filterListings(feed).length,feed.length);
});
test('titles agree grammatically and missing metadata remains visible',()=>{
 const source=feed.find(p=>p.category==='Residenziale');
 const reworked={...source,title:'APPARTAMENTO RISTRUTTURATO',description:'',rooms:null,surface:null,apeStatus:null};
 assert.equal(Rules.displayTitle(reworked),'Appartamento ristrutturato');
 assert.equal(Rules.displayTitle({...reworked,title:'CASA SEMINDIPENDENTE RISTRUTTURATA'}),'Casa semindipendente ristrutturata');
 assert.equal(Rules.displayTitle({...reworked,title:'TRILOCALE CON TERRAZZO'}),'Trilocale con terrazzo');
 assert.equal(Rules.displayData(reworked).rooms,'Locali n.d.');
 assert.equal(Rules.displayData(reworked).surface,'Superficie n.d.');
 assert.equal(Rules.displayData(reworked).ape,'APE da verificare');
 assert.ok(Rules.isEligible({...source,municipality:null,location_status:'DA_VERIFICARE',surface:null}));
 assert.ok(Rules.isEligible({...source,category:'Impresa'}));
 assert.ok(Rules.isEligible({...source,image:'',title:''}));
});
test('prefer a property photo over floorplans or portraits when multiple images exist',()=>{
 const p=feed[0];
 const property='https://cdn.shopify.com/property/front.jpg';
 const plan='https://cdn.shopify.com/property/planimetria.jpg';
 const face='https://cdn.shopify.com/property/agente.jpg';
 assert.equal(Rules.preferredImage({...p,images:[plan,face,property]}),property);
 assert.equal(Rules.preferredImage({...p,images:[],image:plan}),plan);
});
